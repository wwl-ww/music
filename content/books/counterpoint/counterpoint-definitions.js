export function mountScoreDefinition(toolbar, exampleId) {
  const definition = document.createElement('output');
  definition.className = 'counterpoint-score-definition';
  toolbar.querySelector(':scope > fieldset, :scope > label, :scope > .counterpoint-score-controls').before(definition);
  return choice => {
    definition.value = definitions[exampleId][choice];
  };
}
